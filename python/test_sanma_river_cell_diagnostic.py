"""Offline physical-cell calibration tests, not operational authorization."""
import tempfile
import unittest
from pathlib import Path
from PIL import Image
from sanma_river_cell_diagnostic import compare, SLOTS

ROOT = Path(__file__).resolve().parents[1]
FIXTURES = ROOT / 'test/fixtures/sanma-discard-trajectory-122'


class SanmaRiverCellDiagnosticTest(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self.tmp.cleanup)
        self.root = Path(self.tmp.name)

    def path(self, name):
        return FIXTURES / (name + '.png')

    def check_no_authority(self, result):
        self.assertFalse(result['operationAuthorized'])
        self.assertFalse(result['confirmed'])

    def test_observed_discard_and_later_turn(self):
        for name in ('after', 'next_turn'):
            result = compare(self.path('before'), self.path(name))
            self.assertTrue(result['singlePhysicalAppendCandidate'])
            self.assertEqual(result['emptyToTileIndices'], [0])
            self.check_no_authority(result)

    def test_real_pon_and_unchanged_frames_are_not_appends(self):
        for a, b in (('pon_before', 'pon_after'), ('before', 'before'), ('after', 'next_turn')):
            result = compare(self.path(a), self.path(b))
            self.assertFalse(result['singlePhysicalAppendCandidate'])
            self.check_no_authority(result)

    def test_unsupported_size_rejected(self):
        path = self.root / 'small.png'
        Image.new('RGB', (100, 100), 'blue').save(path)
        with self.assertRaises(ValueError):
            compare(path, self.path('after'))

    def test_occluded_or_unloaded_cell_is_unknown(self):
        image = Image.open(self.path('before')).convert('RGB')
        image.paste((0, 0, 0), SLOTS[2])
        path = self.root / 'occluded.png'
        image.save(path)
        result = compare(path, self.path('after'))
        self.assertEqual(result['beforeCells'][2]['state'], 'unknown')
        self.assertFalse(result['singlePhysicalAppendCandidate'])

    def test_existing_tile_mutation_rejected(self):
        image = Image.open(self.path('pon_before')).convert('RGB')
        image.paste((255, 255, 255), SLOTS[0])
        # An apparent tile appears in the first empty slot while an existing
        # tile is altered; neither tile labels nor candidate lists are used.
        image.paste(Image.open(self.path('after')).crop(SLOTS[0]), SLOTS[4])
        path = self.root / 'changed.png'
        image.save(path)
        result = compare(self.path('pon_before'), path)
        self.assertFalse(result['existingTilesUnchangedCandidate'])
        self.assertFalse(result['singlePhysicalAppendCandidate'])

    def test_physical_append_is_not_causal_confirmation(self):
        # Same pixels can be generated by a round change, UI overlay or a
        # different actor. This deliberately demonstrates the missing context.
        before = self.path('before')
        image = Image.open(before).convert('RGB')
        image.paste(Image.open(self.path('after')).crop(SLOTS[0]), SLOTS[0])
        forged = self.root / 'unrelated.png'
        image.save(forged)
        result = compare(before, forged)
        self.assertTrue(result['singlePhysicalAppendCandidate'])
        self.check_no_authority(result)

    def test_independent_match_123_if_available(self):
        root = Path('/home/yama1/server/data/dev-work/jantama/regression-f8728b7-123/artifacts/frames')
        before = list(root.glob('*08-26-20.664177*.sanma-self-turn.png'))
        after = list(root.glob('*08-26-32.464119*.sanma-self-turn.png'))
        if len(before) != 1 or len(after) != 1:
            self.skipTest('independent original evidence unavailable')
        result = compare(before[0], after[0])
        self.assertTrue(result['singlePhysicalAppendCandidate'])
        self.assertEqual(result['emptyToTileIndices'], [0])
        self.check_no_authority(result)

class RiverEvaluationTest(unittest.TestCase):
    def test_counts_are_derived_from_reviewed_pairs(self):
        from sanma_river_cell_evaluation import evaluate
        result = evaluate()
        self.assertEqual(result['counts'], {'truePositive': 2, 'falsePositive': 0,
                                            'trueNegative': 3, 'falseNegative': 0})
        self.assertFalse(result['operationAuthorized'])
        self.assertFalse(result['confirmed'])
        self.assertEqual(len({c['source'] for c in result['cases']}), 2)


if __name__ == '__main__':
    unittest.main()
